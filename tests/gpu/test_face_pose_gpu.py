def _model(mid: str) -> Path:
    manager = ModelManager(DATA / "models")
    entry = manager.manifest.get(mid)
    if entry is None:
        pytest.skip(f"model {mid} is not in the manifest")
    path = manager.path_of(entry)
    if not path.is_file():
        pytest.skip(f"model {mid} is not installed (p11 models install face control)")
    return path


def generate(
    client: TestClient, prompt: str, aspect: str, seed: int, *, steps: list[dict] | None = None
) -> Image.Image:
    """One generation through the API; returns the first image."""
    from tests.helpers import recipe

    from p11.recipe.model import Generate as Gen

    gen = Gen(prompt=prompt, aspect=aspect, batch_size=1)
    r = recipe(gen, *(steps or []), seed=FixedSeed(value=seed), id=f"g-{seed}").model_dump(
        mode="json"
    )
    res = client.post("/api/jobs", json={"recipe": r}, headers=client.token_headers)  # type: ignore[attr-defined]
    assert res.status_code == 201, res.text
    job = wait(client, res.json()["id"])
    assert job["state"] == "done", job.get("error") or job
    return Image.open(io.BytesIO(image_bytes(client, job["images"][0])))


def wait(client: TestClient, job_id: str) -> dict[str, Any]:
    deadline = time.monotonic() + 600
    while time.monotonic() < deadline:
        job = client.get(f"/api/jobs/{job_id}", headers=client.token_headers).json()  # type: ignore[attr-defined]
        if job["state"] in ("done", "failed", "cancelled"):
            return job
        time.sleep(0.25)
    raise AssertionError(f"job {job_id} did not finish")


def image_bytes(client: TestClient, image_id: int) -> bytes:
    res = client.get(f"/api/images/{image_id}", headers=client.token_headers)  # type: ignore[attr-defined]
    assert res.status_code == 200
    return res.content


def upload(client: TestClient, data: bytes) -> str:
    res = client.post("/api/uploads?kind=image", content=data, headers=client.token_headers)  # type: ignore[attr-defined]
    assert res.status_code in (200, 201), res.text
    return res.json()["id"]


def png_bytes(im: Image.Image) -> bytes:
    buf = io.BytesIO()
    im.save(buf, format="PNG")
    return buf.getvalue()


