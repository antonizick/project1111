def test_face_swap_and_restore_on_generated_faces(client) -> None:
    source = generate(client, PORTRAIT, "1:1-1024", 12)
    target = generate(client, PORTRAIT2, "1:1-1024", 13)
    kit = FaceKit(resolve=_model)

    t0 = time.perf_counter()
    faces = kit.detector().detect(np.asarray(target))
    detect_s = time.perf_counter() - t0
    assert faces, "no face in the generated target"

    body = {
        "recipe": {
            **_base_recipe("swap-gpu"),
            "source_image": {"ref": upload(client, png_bytes(target))},
            "slots": [
                {
                    "name": "face",
                    "kind": "face_image",
                    "label": None,
                    "required": True,
                    "default": None,
                }
            ],
            "steps": [
                {
                    "type": "face_swap",
                    "face_slot": "face",
                    "image_slot": None,
                    "source_face_index": 0,
                    "target_face_index": 0,
                    "swapper_model": None,
                    "blend": 1.0,
                    "restore": True,
                    "restore_model": None,
                    "restore_visibility": 1.0,
                }
            ],
        },
        "bindings": {"face": {"ref": upload(client, png_bytes(source))}},
    }
    t0 = time.perf_counter()
    res = client.post("/api/jobs", json=body, headers=client.token_headers)  # type: ignore[attr-defined]
    assert res.status_code == 201, res.text
    job = wait(client, res.json()["id"])
    swap_s = time.perf_counter() - t0
    assert job["state"] == "done", job.get("error") or job
    made = Image.open(io.BytesIO(image_bytes(client, job["images"][0])))
    assert made.size == target.size
    OUT.mkdir(parents=True, exist_ok=True)
    made.save(OUT / "swap-result.png")
    target.save(OUT / "swap-target.png")
    source.save(OUT / "swap-source.png")
    measure(
        step="face_swap",
        seconds=round(swap_s, 2),
        detect_s=round(detect_s, 2),
        size=f"{made.width}x{made.height}",
    )
    # The swapped picture must differ from the target on the face the swap chose.
    box = faces[0].box
    left = target.crop(tuple(int(v) for v in box)).convert("L")
    right = made.crop(tuple(int(v) for v in box)).convert("L")
    diff = sum(abs(a - b) for a, b in zip(left.tobytes(), right.tobytes(), strict=False)) / (
        255 * left.width * left.height
    )
    assert diff > 0.02, f"the face did not change (mean abs diff {diff:.4f})"


def test_the_real_guard_passes_synthetic_faces_and_refuses_before_the_swap(client) -> None:
    from p11.media.nsfw import GuardRefused, check_target

    target = generate(client, PORTRAIT2, "1:1-1024", 21)
    guard = build_guard(_model)
    t0 = time.perf_counter()
    verdict = guard.verdict(target)
    verdict_s = time.perf_counter() - t0
    assert not verdict.unsafe, verdict.scores
    check_target(guard, target)  # no refusal for a normal portrait
    measure(step="nsfw_guard", seconds=round(verdict_s, 2), scores=str(verdict.scores))

    class Missing:
        """The guard must fail closed: without its classifiers a swap does not run."""

    with pytest.raises(Exception, match="Install them"):
        build_guard(lambda mid: Path("/nope") / mid)
    assert Missing is not None
    assert GuardRefused is not None


