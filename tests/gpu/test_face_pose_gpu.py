#: The stock "standing" pose the editor starts from (OpenPose-18, normalised).
STOCK_PERSON = [
    [0.5, 0.16],
    [0.5, 0.26],
    [0.4, 0.27],
    [0.37, 0.42],
    [0.36, 0.56],
    [0.6, 0.27],
    [0.63, 0.42],
    [0.64, 0.56],
    [0.44, 0.55],
    [0.44, 0.73],
    [0.44, 0.9],
    [0.56, 0.55],
    [0.56, 0.73],
    [0.56, 0.9],
    [0.48, 0.14],
    [0.52, 0.14],
    [0.46, 0.15],
    [0.54, 0.15],
]


def pose_distance(made, wanted) -> float:
    """Mean distance between matching visible joints, normalised to the picture (0..1)."""
    total, seen = 0.0, 0
    for a, b in zip(made, wanted, strict=False):
        if a is None or b is None:
            continue
        total += ((a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2) ** 0.5
        seen += 1
    return total / seen if seen else 1.0


def test_apply_pose_follows_a_stock_pose(client) -> None:
    skeleton = render_png(parse_people([STOCK_PERSON]), 896, 1152)
    from tests.helpers import recipe

    from p11.recipe.model import Generate as Gen

    steps = [
        Gen(
            prompt="full body photo of a hiker in a yellow jacket, plain studio background",
            aspect="1:1-1024",
            batch_size=1,
        ),
        Pose(pose_slot="pose", preprocess=False, strength=0.85),
    ]
    r = recipe(
        *steps, slots=(Slot(name="pose", kind="image"),), seed=FixedSeed(value=77), id="pose-gpu"
    ).model_dump(mode="json")
    t0 = time.perf_counter()
    res = client.post(  # type: ignore[attr-defined]
        "/api/jobs",
        json={"recipe": r, "bindings": {"pose": {"ref": upload(client, skeleton)}}},
        headers=client.token_headers,
    )
    assert res.status_code == 201, res.text
    job = wait(client, res.json()["id"])
    seconds = time.perf_counter() - t0
    assert job["state"] == "done", job.get("error") or job
    made = Image.open(io.BytesIO(image_bytes(client, job["images"][0])))
    OUT.mkdir(parents=True, exist_ok=True)
    made.save(OUT / "pose-result.png")
    # The acceptance measure: the figure in the result must stand where the skeleton stood.
    people, _ = extract_people(png_bytes(made), Controls(resolve=_model).pose())
    distance = pose_distance(people[0], parse_people([STOCK_PERSON])[0])
    measure(
        step="generate_with_pose",
        seconds=round(seconds, 2),
        size=f"{made.width}x{made.height}",
        pose_distance=round(distance, 3),
    )
    assert distance < 0.2, (
        f"the figure does not follow the pose (mean joint distance {distance:.3f})"
    )


def test_pose_extraction_finds_the_body(client) -> None:
    target = generate(client, "full body photo of a runner on a plain background", "1:1-1024", 31)
    controls = Controls(resolve=_model)
    t0 = time.perf_counter()
    people, size = extract_people(png_bytes(target), controls.pose())
    seconds = time.perf_counter() - t0
    assert people and len(people[0]) == 18
    assert sum(p is not None for p in people[0]) >= 12
    measure(step="pose_extract", seconds=round(seconds, 2), size=f"{size[0]}x{size[1]}")


