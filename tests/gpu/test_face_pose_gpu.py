def test_reference_keeps_a_style_across_four_seeds(client) -> None:
    from tests.helpers import recipe

    from p11.recipe.model import Generate as Gen

    style = generate(client, "a wooden cabin in a snowy pine forest, watercolour", "1:1-1024", 41)
    ref = upload(client, png_bytes(style))
    made = []
    for seed in (51, 52, 53, 54):
        steps = [
            Gen(prompt="a lighthouse on a cliff at dusk", aspect="1:1-1024", batch_size=1),
            Reference(image_slot="ref", mode="style", weight=0.75),
        ]
        r = recipe(
            *steps,
            slots=(Slot(name="ref", kind="image"),),
            seed=FixedSeed(value=seed),
            id=f"ref-{seed}",
        ).model_dump(mode="json")
        t0 = time.perf_counter()
        res = client.post(  # type: ignore[attr-defined]
            "/api/jobs",
            json={"recipe": r, "bindings": {"ref": {"ref": ref}}},
            headers=client.token_headers,
        )
        assert res.status_code == 201, res.text
        job = wait(client, res.json()["id"])
        seconds = time.perf_counter() - t0
        assert job["state"] == "done", job.get("error") or job
        made.append(Image.open(io.BytesIO(image_bytes(client, job["images"][0]))))
        measure(step="generate_with_reference", seed=seed, seconds=round(seconds, 2))
    assert len(made) == 4
    OUT.mkdir(parents=True, exist_ok=True)
    for i, im in enumerate(made):
        im.save(OUT / f"reference-seed-{51 + i}.png")


def _base_recipe(name: str) -> dict[str, Any]:
    return {
        "schema_version": 1,
        "id": name,
        "name": name,
        "tags": [],
        "folder": "",
        "steps": [],
        "slots": [],
        "seed": {"kind": "fixed", "value": 9},
        "created_at": "2026-11-03T10:00:00+00:00",
    }
